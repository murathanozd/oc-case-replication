"""Projection check (finding F6): does projecting an execution change the directly-follows relation?

Def. 7: E_i^o = {e | i ≤ e ≤ o} is convex wrt. ≤ of D (e ≤ e' ≤ e'' with e, e'' ∈ E_i^o implies
e' ∈ E_i^o). Hence for every object o and e, e'' ∈ E_i^o, every event of o between e and e'' is in
E_i^o, so the DF relation recomputed on Proj_{E_i^o} D equals D's DF restricted to E_i^o.

Def. 11: E_i^o|X̄ is convex only wrt. ≤ of df(D, O \\ X). Events of D that lie between two included
events only via an excluded object's df-edges are dropped, so recomputing DF on the projection can
link events that are not directly-following in D ("spurious"), and DF edges of excluded objects that
are in D come back ("reintroduced").
"""

from __future__ import annotations

from .behaviour import DF, ancestors, descendants, directly_follows, without_objects
from .executions import between, end_of, execution, start_of
from .generalized import end_case, filtered_execution, start_case
from .oced import OCEDSet, natkey


def _key(t):
    return natkey(t[0]), natkey(t[2]), t[1]


def restricted_df(df: DF, evs) -> set[tuple[str, str, str]]:
    """D's DF triples with both events in `evs`."""
    return {t for t in df.triples if t[0] in evs and t[2] in evs}


def convexity_witnesses(df: DF, evs) -> list[str]:
    """Events e' ∉ evs with e ≤ e' ≤ e'' for some e, e'' ∈ evs (≤ of the given DF). Empty iff convex."""
    evs = set(evs)
    if not evs:
        return []
    down = set().union(*(descendants(df, e) for e in evs))
    up = set().union(*(ancestors(df, e) for e in evs))
    return sorted((down & up) - evs, key=natkey)


def check_unfiltered(d: OCEDSet, df: DF, i: str, o: str) -> dict:
    ex = execution(d, df, i, o)
    proj = directly_follows(ex, df.ties).triples
    restr = restricted_df(df, ex.events)
    return {"events": len(ex.events), "convex": not convexity_witnesses(df, ex.events),
            "df_equal": proj == restr, "extra": sorted(proj - restr, key=_key),
            "missing": sorted(restr - proj, key=_key)}


def check_filtered(d: OCEDSet, df: DF, i: str, o: str, X) -> dict:
    """Spurious = DF edges of the projection that are not DF edges of D; reintroduced = DF edges of the
    projection that are DF edges of D on excluded objects. For each spurious edge (a, x, b), the events
    of x strictly between a and b in D that the projection dropped are listed."""
    X = set(X)
    ex = filtered_execution(d, df, i, o, X)
    proj = directly_follows(ex, df.ties).triples
    spurious = []
    for a, x, b in sorted(proj - df.triples, key=_key):
        dropped = sorted((e for e in d.o2e[x] if d.time(a) < d.time(e) < d.time(b)), key=natkey)
        spurious.append({"edge": [a, x, b], "dropped": dropped})
    return {"events": len(ex.events),
            "convex_in_D": not convexity_witnesses(df, ex.events),
            "convex_in_filtered": not convexity_witnesses(without_objects(df, X), ex.events),
            "convexity_witnesses_in_D": convexity_witnesses(df, ex.events),
            "spurious": spurious,
            "reintroduced": sorted((t for t in proj & df.triples if t[1] in X), key=_key),
            "missing": sorted(restricted_df(without_objects(df, X), ex.events) - proj, key=_key)}


def union_check(d: OCEDSet, df: DF, ex: OCEDSet, X) -> dict:
    """Spurious / reintroduced DF edges of a (union of) filtered execution(s) given as an OCED-set."""
    proj = directly_follows(ex, df.ties).triples
    return {"spurious": sorted(proj - df.triples, key=_key),
            "reintroduced": sorted((t for t in proj & df.triples if t[1] in set(X)), key=_key)}


def object_pairs(d: OCEDSet, df: DF, X=frozenset()):
    """All Def. 8 pairs (o_st, o_end) with a non-empty (filtered) execution."""
    out = []
    for s in sorted(d.objects, key=natkey):
        for t in sorted(d.objects, key=natkey):
            i, o = start_of(d, df, s), end_of(d, df, t)
            if between(without_objects(df, X) if X else df, i, o):
                out.append((s, t, i, o))
    return out


def report(d: OCEDSet, df: DF, X) -> str:
    """Markdown for results/r2/projection_check.md (deterministic)."""
    X = set(X)
    xs = ", ".join(sorted(X, key=natkey))
    fmt = lambda t: f"{t[0]} ⋖<sub>{t[1]}</sub> {t[2]}"
    lines = ["# Projection check (R2)", "",
             "Generated by `python -m r2_python.run_all` (`r2_python/projection_check.py`). "
             f"DF ties: `{df.ties}`. Excluded objects for Def. 11: X = {{{xs}}} (all Supplier Orders).", "",
             "## 1. Unfiltered executions (Def. 7 / Def. 8)", "",
             "Check: the DF relation recomputed (Def. 3) on Proj<sub>E_i^o</sub> D equals D's DF restricted "
             "to E_i^o, and E_i^o is convex wrt. ≤ of D.", ""]

    ev_pairs = [(i, o) for i in sorted(d.events, key=natkey) for o in sorted(d.events, key=natkey)
                if between(df, i, o)]
    ev_res = [check_unfiltered(d, df, i, o) for i, o in ev_pairs]
    ok = lambda rs: sum(r["df_equal"] and r["convex"] for r in rs)
    lines += [f"- All event pairs i ≤ o (Def. 7): **{ok(ev_res)} / {len(ev_res)}** executions convex "
              "with DF(projection) = DF(D)|E_i^o.", ""]

    lines += ["| case D[o_st → o_end] | i | o | events | convex | DF(projection) = DF(D)\\|E | extra | missing |",
              "|---|---|---|---|---|---|---|---|"]
    ob_res = []
    for s, t, i, o in object_pairs(d, df):
        r = check_unfiltered(d, df, i, o)
        ob_res.append(r)
        lines.append(f"| D[{s} → {t}] | {i} | {o} | {r['events']} | {'yes' if r['convex'] else 'no'} | "
                     f"{'yes' if r['df_equal'] else 'no'} | {len(r['extra'])} | {len(r['missing'])} |")
    lines += ["", f"All {len(ob_res)} non-empty Def. 8 cases (self-pairs included): "
              f"**{ok(ob_res)} / {len(ob_res)}** pass.", ""]

    lines += ["## 2. Filtered executions (Def. 11)", "",
              "D[i → o \\ X] = Proj<sub>E</sub> D with E = events on a df-path i…o in df(D, O \\ X). "
              "DF is recomputed (Def. 3) on the projection and compared with D's DF:", "",
              "- **spurious**: DF edges of the projection that are not DF edges of D (the events of that "
              "object between the two events in D were dropped by the filter; listed as *dropped*);",
              "- **reintroduced**: DF edges of the projection that are DF edges of D on an excluded object;",
              "- **convex in D / in df(D, O\\X)**: whether E is convex wrt. ≤ of D, resp. of the filtered DF graph.", ""]

    fev = [(i, o) for i in sorted(d.events, key=natkey) for o in sorted(d.events, key=natkey)
           if between(without_objects(df, X), i, o)]
    fres = [check_filtered(d, df, i, o, X) for i, o in fev]
    lines += [f"- All event pairs with a non-empty filtered execution: {len(fres)}; convex in df(D, O\\X): "
              f"{sum(r['convex_in_filtered'] for r in fres)}; convex in D: {sum(r['convex_in_D'] for r in fres)}; "
              f"with spurious edges: {sum(bool(r['spurious']) for r in fres)}; "
              f"with reintroduced edges: {sum(bool(r['reintroduced']) for r in fres)}; "
              f"with filtered-DF edges missing from the projection: {sum(bool(r['missing']) for r in fres)}.", ""]

    lines += ["| case D[o_st → o_end \\ X] | i | o | events | convex in D | convex in df(D, O\\X) | "
              "spurious (dropped events) | reintroduced |", "|---|---|---|---|---|---|---|---|"]
    n = n_sp = n_re = 0
    for s, t, i, o in object_pairs(d, df, X):
        r = check_filtered(d, df, i, o, X)
        n += 1
        n_sp += bool(r["spurious"])
        n_re += bool(r["reintroduced"])
        sp = "; ".join(f"{fmt(x['edge'])} (dropped {', '.join(x['dropped'])})" for x in r["spurious"]) or "–"
        re_ = "; ".join(fmt(x) for x in r["reintroduced"]) or "–"
        cw = "yes" if r["convex_in_D"] else "no (" + ", ".join(r["convexity_witnesses_in_D"]) + ")"
        lines.append(f"| D[{s} → {t} \\ X] | {i} | {o} | {r['events']} | {cw} | "
                     f"{'yes' if r['convex_in_filtered'] else 'no'} | {sp} | {re_} |")
    lines += ["", f"{n} non-empty filtered Def. 8 cases; {n_sp} with spurious edges, {n_re} with reintroduced "
              "edges. \"convex in D = no (…)\" lists the events of D that lie between two included events "
              "but were left out. Non-convexity is necessary but not sufficient for a spurious edge: one also "
              "needs an included object with events on both sides of the dropped ones.", "",
              "## 3. Filtered start and end cases of Orders (Def. 10 + 11, Fig. 11 / 12)", "",
              "The same check on the unions computed in Step 5 (DF recomputed on the union). A union can "
              "reintroduce edges that no single part has (an excluded object with events in different parts).", "",
              "| case | variant | events | spurious | reintroduced |", "|---|---|---|---|---|"]
    orders = sorted((o for o in d.objects if d.type[o] == "Order"), key=natkey)
    for side, fn, cid in (("start", start_case, "{} → * \\ X"), ("end", end_case, "* → {} \\ X")):
        for variant, go in (("global", "full"), ("global", "filtered"), ("any", "full")):
            for o in orders:
                ex = fn(d, df, o, variant, X, go)[0]
                r = union_check(d, df, ex, X)
                name = variant + (f"/{go}" if variant == "global" else "")
                lines.append(f"| D[{cid.format(o)}] | {name} | {len(ex.events)} | "
                             f"{'; '.join(map(fmt, r['spurious'])) or '–'} | "
                             f"{'; '.join(map(fmt, r['reintroduced'])) or '–'} |")
    lines += ["", "## 4. Conclusion", "",
              "- Def. 7: E_i^o is convex, so projecting an execution never changes the DF relation between "
              "its events (no extra, no missing edges).",
              "- Def. 11: E_i^o|X̄ is convex only in df(D, O \\ X), not in D. Recomputing DF on the projection "
              "then creates spurious edges across the dropped events, and the excluded objects' own DF edges "
              "come back. The filtered case, read as an OCED-set, does not have the behaviour that defined it.",
              ""]
    return "\n".join(lines)
